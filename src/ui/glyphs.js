export const GLYPH_HEIGHT = 6;
export const GLYPH_GAP = 1.4; // space between letters, in grid units

/** Glyph for a character (lowercase maps to uppercase; unknown → '?'). */
export function glyphFor(ch) {
  return GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? GLYPHS['?'];
}

/** Width of a line of text in grid units. */
export function textWidth(text) {
  let w = 0;
  const chars = [...text];
  chars.forEach((ch, k) => (w += glyphFor(ch).w + (k < chars.length - 1 ? GLYPH_GAP : 0)));
  return w;
}

/** Characters with no glyph (tests use this to check every UI string can be drawn). */
export function missingGlyphs(text) {
  return [...new Set([...text].filter((ch) => !GLYPHS[ch] && !GLYPHS[ch.toUpperCase()]))];
}
