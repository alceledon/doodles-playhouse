// A hand-made stroke font for the crayon lettering: each glyph is a few
// polylines on a grid 6 units tall (y down, 0 = top, 6 = baseline). crayon.js
// draws them with wobbly waxy strokes. Uppercase, digits and a little
// punctuation: everything the title, day cards and end screens need.

/** Points around an ellipse, as one closed stroke. */
function ellipse(cx, cy, rx, ry, n = 16, start = -Math.PI / 2) {
  const pts = [];
  for (let k = 0; k <= n; k++) {
    const a = start + (k / n) * Math.PI * 2;
    pts.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]);
  }
  return pts;
}

